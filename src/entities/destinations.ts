function normalizeQuery(q: string): string {
  return q.trim().toLowerCase().normalize('NFD').replace(/\p{M}/gu, '');
}

/** Drapeau emoji depuis un code ISO alpha-2 (ex. `FR` → 🇫🇷). */
export function flagEmoji(countryCode: string): string {
  const code = countryCode.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return '';
  return String.fromCodePoint(
    ...[...code].map(c => 0x1f1e6 - 65 + c.charCodeAt(0))
  );
}

export function countryCodeForName(country: string): string {
  const needle = country.trim().toLowerCase();
  if (!needle) return '';
  const hit = DESTINATIONS.find(d => d.country.toLowerCase() === needle);
  return hit?.countryCode ?? '';
}

export function getDestination(id: string): Destination | undefined {
  return DESTINATIONS.find(d => d.id === id);
}

export function destinationsByContinent(
  continent: DestinationContinent
): Destination[] {
  return DESTINATIONS.filter(d => d.continent === continent);
}

export function popularDestinations(limit = 8): Destination[] {
  const out: Destination[] = [];
  for (const id of POPULAR_DESTINATION_IDS) {
    const hit = getDestination(id);
    if (hit) out.push(hit);
    if (out.length >= limit) break;
  }
  return out;
}

/**
 * Autocomplétion : nom, pays, région, lieux « Où aller ».
 * Score simple : préfixe nom > contient nom > pays / lieux.
 */
export function searchDestinations(
  query: string,
  options?: { limit?: number; continent?: DestinationContinent | null }
): Destination[] {
  const q = normalizeQuery(query);
  const limit = options?.limit ?? 12;
  const continent = options?.continent ?? null;
  if (!q) {
    const base = continent
      ? destinationsByContinent(continent)
      : popularDestinations(limit);
    return base.slice(0, limit);
  }

  type Scored = { dest: Destination; score: number };
  const scored: Scored[] = [];
  for (const dest of DESTINATIONS) {
    if (continent && dest.continent !== continent) continue;
    const name = normalizeQuery(dest.name);
    const country = normalizeQuery(dest.country);
    const region = normalizeQuery(dest.region ?? '');
    const places = (dest.places ?? []).map(p => normalizeQuery(p));
    let score = 0;
    if (name === q) score = 100;
    else if (name.startsWith(q)) score = 80;
    else if (name.includes(q)) score = 60;
    else if (country.startsWith(q) || country.includes(q)) score = 40;
    else if (region.includes(q)) score = 35;
    else if (places.some(p => p.startsWith(q) || p.includes(q))) score = 30;
    if (score > 0) scored.push({ dest, score });
  }
  scored.sort(
    (a, b) => b.score - a.score || a.dest.name.localeCompare(b.dest.name, 'fr')
  );
  return scored.slice(0, limit).map(s => s.dest);
}

